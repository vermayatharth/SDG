def main():
    docs, sent = build_sentences()
    hits = get_hits(sent)

    if hits.empty:
        print("\nNo SDG matches identified across the reports with current systems.")
        return

    # Count how many distinct systems flagged each SDG for a given sentence
    sdg = (hits.groupby(["sent_id", "sdg"])["system"].nunique()
               .reset_index(name="n_systems"))
    # Filter by consensus threshold
    sdg = sdg[sdg["n_systems"] >= MIN_SYSTEMS]

    # Aggregate SDGs per sentence
    sdg_agg = (sdg.groupby("sent_id")["sdg"]
                  .apply(lambda x: ";".join(sorted(set(x)))).reset_index(name="sdgs"))
    sdg_sent = sent.merge(sdg_agg, on="sent_id", how="inner")

    # Clarify SDGs with full human-readable titles
    sdg_sent["sdg_clarification"] = sdg_sent["sdgs"].apply(clarify_sdgs)

    print(f"\nSDG Sentences Identified: {len(sdg_sent)} (out of {len(sent)} total sentences)")

    # --- Classify each SDG sentence (Credibility analysis)
    sdg_sent[["time", "detail", "box"]] = sdg_sent["sentence"].apply(
        lambda s: pd.Series(classify(s)))
    sdg_sent.to_csv("sdg_sentences_classified.csv", index=False, encoding="utf-8")
    
    print("\n--- Credibility Classification Breakdown ---")
    print(sdg_sent["box"].value_counts().to_string())

    # --- Summary of Most Prevalent SDGs
    all_matched_sdgs = []
    for s in sdg_sent["sdgs"]:
        all_matched_sdgs.extend(s.split(";"))
    sdg_counts = pd.Series(all_matched_sdgs).value_counts().reset_index()
    sdg_counts.columns = ["sdg", "sentence_count"]
    sdg_counts["goal_title"] = sdg_counts["sdg"].map(SDG_DEFINITIONS)
    sdg_counts.to_csv("sdg_summary_by_goal.csv", index=False)

    print("\n--- Identified SDGs Summary ---")
    for _, row in sdg_counts.head(10).iterrows():
        print(f"  {row['sdg']} ({row['goal_title']}): {row['sentence_count']} sentences")

    # --- Credibility Scores by Firm and Document
    def score(keys):
        g = sdg_sent.groupby(keys)
        out = pd.DataFrame({
            "n_sdg_sentences": g.size(),
            "credible_share":  g["box"].apply(lambda b: (b == "CREDIBLE RESULT").mean()),
            "cheaptalk_share": g["box"].apply(lambda b: (b == "CHEAP TALK").mean()),
            "specific_share":  g["detail"].apply(lambda d: (d == "SPECIFIC").mean()),
            "future_share":    g["time"].apply(lambda t: (t == "FUTURE").mean()),
        }).reset_index()
        out["credibility_net"] = out["credible_share"] - out["cheaptalk_share"]
        out = docs[keys].drop_duplicates().merge(out, on=keys, how="left")
        out["n_sdg_sentences"] = out["n_sdg_sentences"].fillna(0).astype(int)
        return out

    score(["firm_id", "fiscal_year", "year", "doc_type"]).to_csv("sdg_credibility_by_document.csv", index=False)
    score(["firm_id", "fiscal_year", "year"]).to_csv("sdg_credibility_firmyear.csv", index=False)

    # --- Validation sample for human labelling
