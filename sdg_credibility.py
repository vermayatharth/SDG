def make_pattern(words):
    """Whole-word, case-insensitive regex matching longest phrases first."""
    words = sorted(words, key=len, reverse=True)
    alt = "|".join(re.escape(w) for w in words)
    return re.compile(r"(?<![A-Za-z])(" + alt + r")(?![A-Za-z])", re.IGNORECASE)

PAT_FUTURE = make_pattern(FUTURE_WORDS)
PAT_PAST   = make_pattern(PAST_WORDS)

# Reference numbers that are not quantifiable performance metrics
REF_PATTERNS = [
    re.compile(r"\b(SDGs?|Goals?|Targets?)\s*\d+(\.[0-9a-z]+)?", re.I),
    re.compile(r"\bAgenda\s*20\d{2}\b", re.I),
    re.compile(r"\b(GRI|Scope|Principle|Section|Schedule|Annexure|Note|Page|Chapter"
               r"|Clause|Rule|ISO|OHSAS|IS)\s*[-:]?\s*\d[\d.:-]*", re.I),
    re.compile(r"^\s*\d{1,2}[.)]\s+"),               # List numbering like "1." "2)"
]
YEAR_PATTERN = re.compile(r"\b(FY\s*)?(19|20)\d{2}(\s*[-/]\s*\d{2,4})?\b", re.I)


def has_quantity(sentence):
    """Checks whether the sentence contains numerical metrics/quantities."""
    x = sentence
    for p in REF_PATTERNS:
        x = p.sub(" ", x)
    x = YEAR_PATTERN.sub(" ", x)
    return bool(re.search(r"\d", x))


def classify(sentence):
    fut  = bool(PAT_FUTURE.search(sentence))
    past = bool(PAT_PAST.search(sentence))
    spec = has_quantity(sentence)

    if fut and not past:
        time = "FUTURE"
    elif past and not fut:
        time = "PAST"
    elif fut and past:
        time = "MIXED"
    else:
        time = "UNCLEAR"
    detail = "SPECIFIC" if spec else "VAGUE"

    boxes = {
        ("PAST", "SPECIFIC"): "CREDIBLE RESULT",
        ("PAST", "VAGUE"): "VAGUE CLAIM",
        ("FUTURE", "SPECIFIC"): "CONCRETE TARGET",
        ("FUTURE", "VAGUE"): "CHEAP TALK"
    }
    box = boxes.get((time, detail), f"{time} {detail}")
    return time, detail, box


def split_sentences(text):
    """Sentence segmenter with pysbd and fallback."""
    try:
        import pysbd
        seg = split_sentences._seg = getattr(split_sentences, "_seg", None) or \
            pysbd.Segmenter(language="en", clean=False)
        return seg.segment(text)
    except ImportError:
        return re.split(r"(?<=[.!?])\s+(?=[A-Z])", text)


def kappa(a, b):
    labels = sorted(set(a) | set(b))
    n = len(a)
    if n == 0:
        return float("nan")
    po = sum(x == y for x, y in zip(a, b)) / n
    pe = sum((a.count(l) / n) * (b.count(l) / n) for l in labels)
    return (po - pe) / (1 - pe) if pe < 1 else float("nan")

