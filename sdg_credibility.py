def generate_r_code(sentences_csv_path, hits_csv_path, systems):
    systems_str = ", ".join(f'"{s}"' for s in systems)
    # R script escaped for safe execution
    return f'''# Auto-generated R script to run text2sdg
# Setup user library paths
user_lib <- Sys.getenv("R_LIBS_USER")
if (user_lib != "" && dir.exists(user_lib)) {{
  .libPaths(c(user_lib, .libPaths()))
}}

# Ensure text2sdg is installed
if (!requireNamespace("text2sdg", quietly = TRUE)) {{
  message("Installing text2sdg in user library...")
  install.packages("text2sdg", repos = "https://cloud.r-project.org")
}}

suppressPackageStartupMessages(library(text2sdg))

sent_file <- "{sentences_csv_path.replace(os.sep, '/')}"
hits_file <- "{hits_csv_path.replace(os.sep, '/')}"

message("Reading sentences from: ", sent_file)
sent <- read.csv(sent_file, stringsAsFactors = FALSE, encoding = "UTF-8")

message("Detecting SDGs across systems: {', '.join(systems)}")
hits <- detect_sdg_systems(
  sent$sentence,
  systems = c({systems_str}),
  output = "documents"
)

if (!is.null(hits) && nrow(hits) > 0) {{
  hits$document_idx <- as.integer(as.character(hits$document))
  hits$sent_id <- sent$sent_id[hits$document_idx]
  out <- hits[, c("sent_id", "sdg", "system")]
}} else {{
  out <- data.frame(sent_id = integer(0), sdg = character(0), system = character(0))
}}

write.csv(out, hits_file, row.names = FALSE)
message("text2sdg identification complete. Hits saved to: ", hits_file)
'''


def find_rscript():
    """Locate Rscript executable across system PATH and standard Windows install paths."""
    cmd = shutil.which("Rscript")
    if cmd:
        return cmd
    search_patterns = [
        r"C:\Program Files\R\R-*\bin\Rscript.exe",
        r"C:\Program Files\R\R-*\bin\x64\Rscript.exe",
        r"C:\Users\Admin\AppData\Local\Programs\R\R-*\bin\Rscript.exe",
        r"C:\Users\*\AppData\Local\Programs\R\R-*\bin\Rscript.exe",
        r"C:\Program Files (x86)\R\R-*\bin\Rscript.exe",
    ]
    for pattern in search_patterns:
        matches = glob.glob(pattern)
        if matches:
            return sorted(matches)[-1]
    return None


def get_hits(sent):
    """Identifies SDGs using text2sdg in R."""
    script_dir = os.path.dirname(os.path.abspath(__file__))
    sent_path = os.path.join(script_dir, SENTENCES_FILE)
    hits_path = os.path.join(script_dir, HITS_FILE)

    # Check if existing hits file matches current sentences
    if os.path.exists(hits_path) and os.path.exists(sent_path):
        try:
            old = pd.read_csv(sent_path, usecols=["sent_id", "sentence"],
                              dtype={"sentence": str}, keep_default_na=False)
            same = (len(old) == len(sent)
                    and (old["sentence"].values == sent["sentence"].values).all())
            if same and os.path.getmtime(hits_path) >= os.path.getmtime(sent_path):
                print(f"Reusing existing SDG hits from {hits_path}")
                return pd.read_csv(hits_path)
        except Exception:
            pass

    if os.path.exists(hits_path):
        os.remove(hits_path)
    sent.to_csv(sent_path, index=False, encoding="utf-8")

    r_script_code = generate_r_code(sent_path, hits_path, SDG_SYSTEMS)

    if SDG_MODE in ("auto", "file"):
        rscript = find_rscript()
        if rscript:
            print(f"\n[text2sdg] Found Rscript at: {rscript}")
            print(f"[text2sdg] Running SDG identification using systems: {', '.join(SDG_SYSTEMS)}...")
            r_run_file = os.path.join(script_dir, "run_text2sdg.R")
            with open(r_run_file, "w", encoding="utf-8") as f:
                f.write(r_script_code)
            try:
                subprocess.run([rscript, r_run_file], check=True)
                if os.path.exists(hits_path):
                    return pd.read_csv(hits_path)
            except Exception as e:
                print(f"[text2sdg] Subprocess R execution failed: {e}")

    # Fallback to manual execution prompt
    print(f"\nWrote {sent_path}. Please execute this in R to proceed:")
    print(r_script_code)
    sys.exit(0)


def clarify_sdgs(sdg_code_string):
    """Clarifies SDG codes into human-readable UN SDG descriptions."""
    if not isinstance(sdg_code_string, str) or not sdg_code_string.strip():
        return ""
    codes = sdg_code_string.split(";")
    labels = [f"{c}: {SDG_DEFINITIONS.get(c, 'Unknown Goal')}" for c in codes]
    return "; ".join(labels)

