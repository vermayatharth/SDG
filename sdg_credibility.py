r"""
SDG CREDIBILITY SCORE  —  rule-based (no AI model)   |  Python version with text2sdg (R)

What it does:
 1. Extracts text from report PDFs (or .txt) across fiscal-year folders.
 2. Breaks each report into sentences using pysbd.
 3. Identifies and clarifies SDGs for each sentence using the text2sdg R library
    (using Aurora, Elsevier, and SIRIS consensus systems).
 4. For every SDG sentence, classifies:
      Q1: Is it a PROMISE (future) or a PROOF (past)?
      Q2: Is it VAGUE or SPECIFIC (does it provide verifiable numeric quantities)?
 5. Generates firm-year credibility scores:
      credible_share  = % of SDG sentences that are PAST + SPECIFIC
      cheaptalk_share = % of SDG sentences that are FUTURE + VAGUE
 6. Exports classified sentences with full SDG names, per-document credibility metrics,
    and a 500-sentence validation sample for human agreement checking.

R is automatically invoked via Rscript to run text2sdg.
"""

