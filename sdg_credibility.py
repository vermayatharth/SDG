FY_PATTERN = re.compile(r"((?:19|20)\d{2})\s*[-\u2013_/ ]\s*(\d{2,4})(?!\d)")
DOC_TYPES = [
    ("BRSR", r"\bBRSR\b|business responsibility (?:and|&) sustainability"),
    ("BRR",  r"\bBRR\b|business responsibility report"),
    ("SR",   r"sustainability report|\bESG report\b|\bSR\b"),
    ("AR",   r"\bAR\b|annual report|integrated report"),
]
LEGAL_WORDS = r"\b(LTD|LIMITED|PVT|PRIVATE|CO|COMPANY|CORP|CORPORATION|INC|THE)\b"


def fiscal_year(text):
    m = FY_PATTERN.search(text)
    if not m:
        return None
    start = int(m.group(1))
    end2 = m.group(2)
    end = int(end2) if len(end2) == 4 else (start // 100) * 100 + int(end2)
    if end != start + 1:
        return None
    return f"{start}-{str(end)[-2:]}", (end if YEAR_AS == "end" else start)


def parse_name(stem):
    x = re.sub(r"[_\-.]+", " ", stem)
    doc = "ALL"
    for label, pat in DOC_TYPES:
        if re.search(pat, x, re.I):
            doc = label
            x = re.sub(pat, " ", x, flags=re.I)
            break
    x = FY_PATTERN.sub(" ", x)
    x = re.sub(r"\b(FY)?\s*(19|20)\d{2}\b", " ", x, flags=re.I)
    x = x.upper().replace("&", " AND ")
    x = re.sub(r"[^A-Z0-9 ]", " ", x)
    x = re.sub(LEGAL_WORDS, " ", x)
    firm = "_".join(x.split())
    return firm, doc


def pdf_to_text(path):
    try:
        import pymupdf
        with pymupdf.open(path) as doc:
            return "\n".join(page.get_text() for page in doc), len(doc)
    except ImportError:
        # pyrefly: ignore [missing-import]
        from pypdf import PdfReader
        r = PdfReader(path)
        return "\n".join((p.extract_text() or "") for p in r.pages), len(r.pages)


def count_pages(path):
    try:
        import pymupdf
        with pymupdf.open(path) as doc:
            return len(doc)
    except Exception:
        return None


def clean_pdf_text(text):
    text = text.replace("\ufeff", "")
    text = re.sub(r"(\w)-\n(\w)", r"\1\2", text)
    text = re.sub(r"\n\s*\n+", " \u2029 ", text)
    text = re.sub(r"[ \t]*\n[ \t]*", " ", text)
    text = text.replace("\u2029", "\n\n")
    return re.sub(r"[ \t]+", " ", text)


def build_sentences():
    folder = REPORTS_FOLDER
    script_dir = os.path.dirname(os.path.abspath(__file__))
    if not os.path.isabs(folder):
        cand = os.path.join(script_dir, folder)
        if os.path.isdir(cand):
            folder = cand
        elif os.path.isdir(script_dir):
            folder = script_dir
    if not os.path.isdir(folder):
        sys.exit(f"Folder not found: {folder}\nPlease create or point REPORTS_FOLDER in SETTINGS to your reports directory.")
    os.makedirs(TEXT_FOLDER, exist_ok=True)

    files = []
    # Ignored filenames (output/intermediate artifacts)
    ignore_prefixes = ("sdg_", "test_", "run_", "extraction_")
    ignore_substrings = ("with_sdg_report", "credibility_report")

    for root, _, names in os.walk(folder):
        # Don't recurse into cache/extracted_text folder
        if os.path.abspath(root).startswith(os.path.abspath(TEXT_FOLDER)):
            continue
        for n in names:
            nl = n.lower()
            if nl.endswith((".pdf", ".txt")):
                if nl.startswith(ignore_prefixes) or any(sub in nl for sub in ignore_substrings):
                    continue
                files.append(os.path.join(root, n))
    files.sort()
    if not files:
        sys.exit(f"No .pdf or .txt files found under {folder}")

    docs, rows, log = [], [], []
    for i, path in enumerate(files, 1):
        rel = os.path.relpath(path, folder)
        stem, ext = os.path.splitext(os.path.basename(path))

        parts = [os.path.basename(os.path.normpath(folder))] + rel.split(os.sep)
        fy = None
        for part in reversed(parts[:-1]):
            fy = fiscal_year(part)
            if fy:
                break
        fy = fy or fiscal_year(stem)
        if not fy and ext.lower() == ".pdf":
            try:
                import pymupdf
                with pymupdf.open(path) as d_:
                    sample = "\n".join(d_[j].get_text() for j in range(min(5, len(d_))))
                    fy = fiscal_year(sample)
            except Exception:
                pass
        if not fy:
            print(f"  SKIPPED (no year like 2018-19 in folder or file name): {rel}")
            log.append({"file": rel, "status": "no year found"})
            continue
        fy_label, year = fy
        if ONLY_YEARS and fy_label not in ONLY_YEARS:
            continue
        print(f"  Processing: {rel}")
        firm, doctype = parse_name(stem)
        if doctype == "ALL" and ext.lower() == ".pdf":
            try:
                import pymupdf
                with pymupdf.open(path) as d_:
                    sample_doc = "\n".join(d_[j].get_text() for j in range(min(5, len(d_))))
                    for label, pat in DOC_TYPES:
                        if re.search(pat, sample_doc, re.I):
                            doctype = label
                            break
            except Exception:
                pass
        if not firm:
            print(f"  SKIPPED (no firm name in file name): {rel}")
            log.append({"file": rel, "status": "no firm name"})
            continue

        cache = os.path.join(TEXT_FOLDER, os.path.splitext(rel)[0] + ".txt")
        os.makedirs(os.path.dirname(cache), exist_ok=True)
        pages = None
        if os.path.exists(cache):
            text = open(cache, encoding="utf-8").read()
            if ext.lower() == ".pdf":
                pages = count_pages(path)
        elif ext.lower() == ".pdf":
            try:
                raw, pages = pdf_to_text(path)
            except Exception as e:
                print(f"     ERROR reading PDF: {e}")
                log.append({"file": rel, "status": f"error: {e}"})
                continue
            text = clean_pdf_text(raw)
            open(cache, "w", encoding="utf-8").write(text)
        else:
            text = open(path, encoding="utf-8", errors="ignore").read()

        n_words = len(text.split())
        status = "ok"
        if (pages and n_words / pages < 50) or n_words == 0:
            status = "LOW TEXT - probably scanned, needs OCR"
            print(f"     WARNING: {status}")

        n_before = len(rows)
        for s_ in split_sentences(text):
            s_ = re.sub(r"\s+", " ", s_).strip()
            if len(s_.split()) >= 5:
                rows.append({
                    "firm_id": firm,
                    "fiscal_year": fy_label,
                    "year": year,
                    "doc_type": doctype,
                    "sentence": s_
                })
        docs.append({
            "firm_id": firm,
            "fiscal_year": fy_label,
            "year": year,
            "doc_type": doctype,
            "file": rel
        })
        log.append({
            "file": rel,
            "firm_id": firm,
            "fiscal_year": fy_label,
            "year": year,
            "doc_type": doctype,
            "pages": pages,
            "words": n_words,
            "sentences": len(rows) - n_before,
            "status": status
        })

    log = pd.DataFrame(log)
    for c in ["year", "pages", "words", "sentences"]:
        if c in log:
            log[c] = log[c].astype("Int64")
    log.to_csv("extraction_log.csv", index=False)

    docs = pd.DataFrame(docs)
    if docs.empty:
        sys.exit(f"No reports found for {ONLY_YEARS or 'any year'}. Check REPORTS_FOLDER and ONLY_YEARS.")
    dup = docs[docs.duplicated(["firm_id", "year", "doc_type"], keep=False)]
    if len(dup):
        dup.to_csv("duplicate_firm_years.csv", index=False)
        print(f"  WARNING: {len(dup)} files share the same firm-year-doc_type -> duplicate_firm_years.csv")

    if len(docs):
        (docs.assign(present=1)
             .pivot_table(index="firm_id", columns="fiscal_year", values="present",
                          aggfunc="sum", fill_value=0)
             .to_csv("firm_coverage_by_year.csv"))

    sent = pd.DataFrame(rows)
    sent.insert(0, "sent_id", range(1, len(sent) + 1))
    print(f"Total Sentences Extracted: {len(sent)}")
    return docs, sent

